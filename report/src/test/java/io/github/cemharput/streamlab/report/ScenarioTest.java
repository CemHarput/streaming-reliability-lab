package io.github.cemharput.streamlab.report;

import static org.assertj.core.api.Assertions.assertThat;

import io.github.cemharput.streamlab.bench.Flags;
import io.github.cemharput.streamlab.report.testsupport.Cli;
import io.github.cemharput.streamlab.report.testsupport.Cli.Result;
import io.github.cemharput.streamlab.report.testsupport.ResultSetBuilder;
import io.github.cemharput.streamlab.report.testsupport.ResultSetBuilder.Req;
import io.github.cemharput.streamlab.report.testsupport.Scans;
import io.github.cemharput.streamlab.report.testsupport.Scenarios;
import java.io.IOException;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.List;
import java.util.concurrent.TimeUnit;
import org.junit.jupiter.api.BeforeEach;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.Timeout;
import org.junit.jupiter.api.Timeout.ThreadMode;
import org.junit.jupiter.api.io.TempDir;

/** End to end over synthetic sets: the report of every scenario, scanned for wording and privacy. */
@Timeout(value = 60, unit = TimeUnit.SECONDS, threadMode = ThreadMode.SEPARATE_THREAD)
class ScenarioTest {

    @TempDir
    Path tmp;

    Path out;

    @BeforeEach
    void outDir() throws IOException {
        out = Files.createDirectory(tmp.resolve("out"));
    }

    private Result analyse(ResultSetBuilder b) throws IOException {
        Path set = b.build();
        Result r = Cli.run(tmp, "--results", set.toString(), "--out", out.toString(), "--allow-smoke");
        assertThat(r.exit()).as(r.err()).isZero();
        Scans.assertClean(out, r.out(), List.of(tmp));
        return r;
    }

    private String report() throws IOException {
        return Files.readString(out.resolve("benchmark-report.md"));
    }

    @Test
    void theElevenSectionsAppearInOrder() throws Exception {
        analyse(Scenarios.mixed(tmp));
        String text = report();
        int last = -1;
        int n = 0;
        for (String title : ReportRenderer.SECTION_TITLES) {
            n++;
            int at = text.indexOf("\n## " + n + ". " + title + "\n");
            assertThat(at).as(title).isGreaterThan(last);
            last = at;
        }
        assertThat(text.lines().findFirst().orElseThrow()).isEqualTo("<!-- Generated by the report module (analysis"
                + " version 1) from result set 20260101T000000Z-abc1234-fixture. Do not edit; regenerate (see \"How to"
                + " regenerate\"). -->");
        assertThat(ReportRenderer.SECTION_TITLES).hasSize(11);
    }

    @Test
    void aMixedSetShowsEveryRunWithItsClassAndReasons() throws Exception {
        analyse(Scenarios.mixed(tmp));
        String text = report();
        assertThat(text).contains("| 3 | 003-c4-per-request-r2 | per-request | 4 | 2 | BA | 1st | completed | caution |"
                + " `MEASURED:OUTCOME_TIMEOUT_NONZERO` |");
        assertThat(text).contains("| 5 | 005-c4-shared-r3 | shared | 4 | 3 | AB | 1st | completed | excluded |"
                + " `RUN:CPU_BUSY_BEFORE_RUN` |");
        assertThat(text).contains("| 6 | 006-c4-per-request-r3 | per-request | 4 | 3 | AB | 2nd | failed | excluded |"
                + " `STATUS:STATUS_FAILED` |");
        assertThat(text).contains("`MEASURED:REJECTED_AT_OR_BELOW_LIMIT`").contains("`RUN:TIMEOUTS_DELTA_NONZERO`");
        // the rejected-heavy run keeps its numbers: 40 of 50 lines
        assertThat(text).contains("| #7 007-c4-per-request-r4* | 50 | 10 (20.00 %) | 40 (80.00 %) |");
        // excluded runs are shown in the metrics but are not in the comparison tables
        assertThat(text).contains("#5 005-c4-shared-r3 (excluded)");
        assertThat(text).doesNotContain("#5 1st").doesNotContain(" #6 2nd");
    }

    @Test
    void theComparisonShowsRepetitionsSideBySideWithIndexAndPosition() throws Exception {
        analyse(Scenarios.clean(tmp));
        String text = report();
        assertThat(text).contains("### Concurrency 2").contains("### Concurrency 4");
        assertThat(text).contains("| Repetition | shared | per-request |");
        assertThat(text).containsPattern("\\| 1 \\| [0-9.]+ #1 1st \\| [0-9.]+ #2 2nd \\|");
        assertThat(text).containsPattern("\\| 2 \\| [0-9.]+ #4 2nd \\| [0-9.]+ #3 1st \\|");
        assertThat(text).containsPattern("\\| shared \\| 4 \\| ");
        assertThat(text).contains("In this result set, at concurrency 2, the median time to first chunk p50 of");
        assertThat(text).doesNotContainIgnoringCase("pooled percentile:");
    }

    @Test
    void theLimitsBlockIsQuotedAndTheCaveatsAreStated() throws Exception {
        analyse(Scenarios.clean(tmp));
        String text = report();
        assertThat(text).contains(ReportText.limitsBlock());
        for (String caveat : List.of("time to first byte is the arrival of the response headers", "buffer arrival",
                "coordinated omission", "reject pause", "one machine", "not a capacity measurement")) {
            assertThat(text.replace("\n", " ")).as(caveat).contains(caveat.replace("\n", " "));
        }
        assertThat(text).contains("**Time to first byte (ttfb).**").contains("**Reject pause.**")
                .contains("**Same machine.**").contains("**Closed model.**");
    }

    @Test
    void theReportStatesThatComparisonCellsUseAsManyDecimalsAsNeeded() throws Exception {
        analyse(Scenarios.clean(tmp));
        String text = report().replaceAll("\\s+", " ");
        assertThat(text).contains("as many decimals as are needed to keep the facts the rule used visible")
                .contains("there times are not rounded to microseconds first")
                .contains("The rule itself always uses the exact values");
    }

    @Test
    void theDataQualitySectionHasTheCrossChecksEnvironmentAndTheListedFiles() throws Exception {
        analyse(Scenarios.clean(tmp));
        String text = report();
        for (int i = 1; i <= 12; i++) {
            assertThat(text).contains("| C" + i + " |");
        }
        assertThat(text).contains("### CPU load samples").contains("### TIME_WAIT sockets").contains("### Artifacts")
                .contains("0123456789abcdef0123456789abcdef0123456789abcdef0123456789abcdef")
                .contains("### Stop records and logs").contains("GC logs and process logs (listed, not analysed)")
                .contains("gateway-gc.log").contains("Git commit").contains("Git working tree dirty")
                .contains("Operator checklist source").contains("Set status");
    }

    @Test
    void theFlagTableOfTheReportIsGeneratedFromThePolicy() throws Exception {
        analyse(Scenarios.clean(tmp));
        String text = report();
        for (FlagPolicy.Entry e : FlagPolicy.entries()) {
            assertThat(text).contains("| " + Fmt.cell(Fmt.code(e.name())) + " | " + e.severity().label() + " | " + e.scope() + " |");
        }
        for (String code : Checks.TABLE.keySet()) {
            assertThat(text).contains("| `" + code + "` | " + Checks.TABLE.get(code).label() + " | check |");
        }
    }

    @Test
    void aMalformedJsonlLineExcludesTheRunAndShowsOnlyTheLineNumber() throws Exception {
        ResultSetBuilder b = Scenarios.clean(tmp);
        b.run(3).extraJsonlLines.add("{\"type\":\"request\", this is broken fixtureuser");
        analyse(b);
        String text = report();
        assertThat(text).contains("`CHECK:CHECK_JSONL_MALFORMED_LINE`").contains("1 line(s) skipped");
        assertThat(text).doesNotContain("this is broken");
        assertThat(text).contains("| 3 | 003-c2-per-request-r2 |");
    }

    @Test
    void anUnsupportedJsonlSchemaExcludesOnlyThatRun() throws Exception {
        ResultSetBuilder b = Scenarios.clean(tmp);
        b.run(2).headerOverrides.put("schemaVersion", 7L);
        Result r = analyse(b);
        assertThat(r.summary()).containsEntry("excluded", 1L);
        assertThat(report()).contains("`CHECK:CHECK_JSONL_SCHEMA_UNSUPPORTED`");
        assertThat(r.out()).contains("excluded 002-c2-per-request-r1: CHECK:CHECK_JSONL_SCHEMA_UNSUPPORTED");
    }

    @Test
    void aFailedAndAnInterruptedSetAreReportedWithoutNumbersForMissingRuns() throws Exception {
        ResultSetBuilder b = ResultSetBuilder.at(tmp.resolve("failed")).concurrency(4).repetitions(2)
                .setStatus("failed").plan();
        b.run(1).status("failed").writeJsonl = false;
        b.run(1).writeSnapshots = false;
        b.run(2).status("not_run");
        b.run(3).status("not_run");
        b.run(4).status("not_run");
        analyse(b);
        String text = report();
        assertThat(text).contains("**Set incomplete:").contains("Harness failure text | present (text not reproduced)");
        assertThat(text).contains("No included run has a value for this metric.");
        assertThat(text).contains("In this result set, at concurrency 4, there were fewer than two usable repetitions");
        assertThat(text).contains("| #1 001-c4-shared-r1 (excluded) | n/a | n/a |");
    }

    @Test
    void aMinimalFailedManifestWithoutRunsIsReported() throws Exception {
        Path dir = Files.createDirectories(tmp.resolve("minimal"));
        Files.writeString(dir.resolve("manifest.json"), "{\"schemaVersion\":1,\"protocolVersion\":1,"
                + "\"runId\":\"minimal-fixture\",\"tool\":\"streamlab-bench\",\"status\":\"failed\","
                + "\"harnessFailure\":\"failed in /home/fixtureuser/x\"}");
        Result r = Cli.run(tmp, "--results", dir.toString(), "--out", out.toString());
        assertThat(r.exit()).isZero();
        assertThat(r.summary()).containsEntry("runs", 0L);
        Scans.assertClean(out, r.out(), List.of(tmp));
        assertThat(report()).contains("The manifest lists no runs");
    }

    @Test
    void aRejectedHeavySetStillComparesAndCarriesTheCaution() throws Exception {
        ResultSetBuilder b = Scenarios.mixed(tmp);
        Result r = analyse(b);
        assertThat(r.summary()).containsEntry("caution", 3L);
        assertThat(report()).contains("share of REJECTED requests (%)");
    }

    @Test
    void anOutcomeThatTheToolDoesNotKnowIsCountedAndShown() throws Exception {
        ResultSetBuilder b = Scenarios.clean(tmp);
        List<Req> reqs = new ArrayList<>(List.of(Req.completed(1500, 1, 2, 3), Req.of("BRAND_NEW_OUTCOME", 2000, 5)));
        b.run(1).requests(reqs);
        analyse(b);
        assertThat(report()).contains("BRAND_NEW_OUTCOME").contains("1 (50.00 %)");
    }

    @Test
    void aSetFlagThatIsOnlyACautionShowsAsABanner() throws Exception {
        ResultSetBuilder b = Scenarios.clean(tmp).setFlag(Flags.GIT_DIRTY);
        Result r = analyse(b);
        assertThat(report()).contains("> Caution flags recorded for the whole set: `GIT_DIRTY`.");
        assertThat(r.summary()).containsEntry("excluded", 0L);
    }

    @Test
    void warmUpAnomaliesAreCautionsAndNeverExclusions() throws Exception {
        ResultSetBuilder b = Scenarios.clean(tmp);
        b.run(1).warmupFlag(Flags.GATEWAY_EXITED);
        Result r = analyse(b);
        assertThat(r.summary()).containsEntry("caution", 1L).containsEntry("excluded", 0L);
        assertThat(report()).contains("`WARMUP:GATEWAY_EXITED`");
    }
}
