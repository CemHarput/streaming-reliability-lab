    private ReportText() {
    }

    public static String firstLine(String runId) {
        return MARKER_PREFIX + " from result set " + safeComment(runId)
                + ". Do not edit; regenerate (see \"How to regenerate\"). -->\n";
    }

    /** The run id inside an HTML comment: only a safe alphabet, no {@code --}, no angle brackets, no line breaks. */
    static String safeComment(String text) {
        String s = text.length() > 120 ? text.substring(0, 120) : text;
        s = s.replaceAll("[^A-Za-z0-9._:+-]", "_");
        while (s.contains("--")) {
            s = s.replace("--", "-_");
        }
        return s;
    }

    public static String placeholderFirstLine() {
        return MARKER_PREFIX + " as a placeholder: no result set analysed yet."
                + " Do not edit; regenerate (see \"How to regenerate\"). -->\n";
    }

    /** The quoted limits wrapped in the markers the wording guard recognises. */
    public static String limitsBlock() {
        return WordingGuard.BEGIN + "\n" + QUOTED_LIMITS + WordingGuard.END + "\n";
    }
